object DotMetrics {
    /** Rendered width of [text] on the grid: 5 columns + 1 column advance per glyph. */
    fun width(text: String, dot: Dp, gap: Dp): Dp = (dot + gap) * 6 * text.length - gap

    fun height(dot: Dp, gap: Dp): Dp = (dot + gap) * 7
}

/**
 * Draws [text] on the SankOS dot grid, centered within the layout bounds.
 *
 * @param dot    diameter of a lit dot
 * @param gap    spacing between dot centers minus diameter
 * @param color  color of lit dots
 * @param gridColor optional faint color for unlit grid dots
 */
@Composable
fun DotText(
    text: String,
    modifier: Modifier = Modifier,
    dot: Dp = 2.dp,
    gap: Dp = 1.dp,
    color: Color,
    gridColor: Color = Color.Transparent,
) {
    Canvas(modifier) {
        val cell = (dot + gap).toPx()
        val radius = dot.toPx() / 2f
        val advance = 6 * cell
        val totalW = advance * text.length - gap.toPx()
        val totalH = 7 * cell
        val originX = (size.width - totalW) / 2f
        val originY = (size.height - totalH) / 2f

        text.forEachIndexed { i, raw ->
            val rows = DotGlyphs.rows(raw) ?: DotGlyphs.rows(' ') ?: return@forEachIndexed
            val gx = originX + i * advance
            for (r in 0..6) {
                val bits = rows[r].toInt() and 0xFF
                for (c in 0..4) {
                    val cx = gx + c * cell + cell / 2f
                    val cy = originY + r * cell + cell / 2f
                    if (((bits shr (4 - c)) and 1) == 1) {
                        drawCircle(color = color, radius = radius, center = Offset(cx, cy))
                    } else if (gridColor != Color.Transparent) {
                        drawCircle(color = gridColor, radius = radius * 0.45f, center = Offset(cx, cy))
                    }
                }
            }
        }
    }
}
