/**
 * SankOS dot-matrix engine.
 *
 * A 5x7 dot grid per glyph, rendered as circles on Canvas. "Off" dots are
 * optionally drawn faint to expose the underlying grid — the industrial
 * texture used across SankOS for machine information (date, labels, marks).
 *
 * The glyph set is an original 5x7 bitmap collection defined in code; it is
 * the source of the SankOS "S" launcher mark and can be swapped for custom
